package spanalyzer

import "testing"

// These are source-backed model regressions, not additional managed probes.
// The DDL/DML reference audit records the automatic-column semantics; no test
// evaluates a generated SQL expression or assigns it an observed service price.
func TestMutationCountVirtualGeneratedIndexDependencies(t *testing.T) {
	a := mutationTestAnalyzer(t, `CREATE TABLE T(Id INT64 NOT NULL,V STRING(MAX),U STRING(MAX),G INT64 AS (LENGTH(V))) PRIMARY KEY(Id);
CREATE INDEX ByG ON T(G);`)
	for _, tc := range []struct {
		column string
		hi     int64
	}{{"V", 4}, {"U", 2}} {
		r, err := a.AnalyzeDML([]string{"UPDATE T SET " + tc.column + "='same' WHERE Id=1"}, MutationCountOptions{Facts: []MutationCountRowFacts{{Rows: mutationTestInt(1), Exists: mutationTestBool(true), Old: map[string]interface{}{"V": "same", "G": "4"}}}})
		if err != nil {
			t.Fatal(err)
		}
		assertMutationInterval(t, r.Effective, 2, mutationTestInt(tc.hi))
		assertMutationInterval(t, r.OldRows.Results[0].IndexEffects[0].Count, 0, mutationTestInt(tc.hi-2))
	}

	a = mutationTestAnalyzer(t, `CREATE TABLE T(Id INT64 NOT NULL,V STRING(MAX),G INT64 AS (LENGTH(V))) PRIMARY KEY(Id);
CREATE NULL_FILTERED INDEX ByG ON T(G);`)
	r, err := a.AnalyzeDML([]string{"INSERT INTO T(Id,V) VALUES(1,'x')"}, MutationCountOptions{})
	if err != nil {
		t.Fatal(err)
	}
	// An omitted virtual column is unknown, not an implicit NULL. It adds no
	// base cell, but its index entry cannot be ruled out without evaluation.
	assertMutationInterval(t, r.Bounds.Count, 2, mutationTestInt(3))
	assertMutationInterval(t, r.Bounds.Results[0].IndexEffects[0].Count, 0, mutationTestInt(1))

	a = mutationTestAnalyzer(t, `CREATE TABLE T(Id INT64 NOT NULL,V STRING(MAX),U STRING(MAX),G INT64 AS (LENGTH(V))) PRIMARY KEY(Id);
CREATE INDEX ByU ON T(U) STORING(G);`)
	r, err = a.AnalyzeDML([]string{"UPDATE T SET V='new' WHERE Id=1"}, MutationCountOptions{Facts: []MutationCountRowFacts{{Rows: mutationTestInt(1), Exists: mutationTestBool(true), Old: map[string]interface{}{"U": "a", "G": "3"}}}})
	if err != nil {
		t.Fatal(err)
	}
	assertMutationInterval(t, r.Effective, 2, mutationTestInt(4))
	assertMutationInterval(t, r.OldRows.Results[0].IndexEffects[0].Count, 0, mutationTestInt(2))
}

func TestMutationCountTransitiveGeneratedIndexDependencies(t *testing.T) {
	for _, columns := range []string{
		"G INT64 AS (LENGTH(V)),H INT64 AS (G+1) STORED",
		"G INT64 AS (LENGTH(V)) STORED,H INT64 AS (G+1)",
	} {
		a := mutationTestAnalyzer(t, "CREATE TABLE T(Id INT64 NOT NULL,V STRING(MAX),"+columns+") PRIMARY KEY(Id); CREATE INDEX ByH ON T(H);")
		r, err := a.AnalyzeDML([]string{"UPDATE T SET V='new' WHERE Id=1"}, MutationCountOptions{Facts: []MutationCountRowFacts{{Rows: mutationTestInt(1), Exists: mutationTestBool(true), Old: map[string]interface{}{"G": "3", "H": "4"}}}})
		if err != nil {
			t.Fatal(err)
		}
		assertMutationInterval(t, r.Effective, 2, nil)
		assertMutationInterval(t, r.OldRows.Results[0].IndexEffects[0].Count, 0, mutationTestInt(2))
	}
}

