func TestMutationCountOnUpdateIndexDependencies(t *testing.T) {
	a := mutationTestAnalyzer(t, `CREATE TABLE T(Id INT64 NOT NULL,V STRING(MAX),Stamp TIMESTAMP DEFAULT (PENDING_COMMIT_TIMESTAMP()) ON UPDATE (PENDING_COMMIT_TIMESTAMP()) OPTIONS(allow_commit_timestamp=true)) PRIMARY KEY(Id);
CREATE INDEX ByStamp ON T(Stamp);`)
	options := MutationCountOptions{Facts: []MutationCountRowFacts{{Rows: mutationTestInt(1), Exists: mutationTestBool(true), Old: map[string]interface{}{"V": "same", "Stamp": "2026-11-09T00:00:00Z"}}}}
	r, err := a.AnalyzeDML([]string{"UPDATE T SET V='same' WHERE Id=1"}, options)
	if err != nil {
		t.Fatal(err)
	}
	// ON UPDATE fires even for a same-value non-key write. The new timestamp
	// is unknown; copying the old value would incorrectly erase index effects.
	assertMutationInterval(t, r.Effective, 2, nil)
	assertMutationInterval(t, r.OldRows.Results[0].IndexEffects[0].Count, 0, mutationTestInt(2))
	r, err = a.AnalyzeWriteShape(MutationWriteShape{Operation: "update", Table: "T", Columns: []string{"Id", "V", "Stamp"}, Values: map[string]interface{}{"Id": "1", "V": "same", "Stamp": "2026-11-10T00:00:00Z"}}, options)
	if err != nil {
		t.Fatal(err)
	}
	// An explicitly supplied timestamp bypasses ON UPDATE.
	assertMutationInterval(t, r.Effective, 5, mutationTestInt(5))
}

func TestMutationCountUnknownWriteDoesNotReuseOldValue(t *testing.T) {
	a := mutationTestAnalyzer(t, `CREATE TABLE T(Id INT64 NOT NULL,V STRING(MAX)) PRIMARY KEY(Id); CREATE INDEX ByV ON T(V);`)
	options := MutationCountOptions{Facts: []MutationCountRowFacts{{Rows: mutationTestInt(1), Exists: mutationTestBool(true), Old: map[string]interface{}{"V": "a"}}}}
	r, err := a.AnalyzeDML([]string{"UPDATE T SET V=UPPER(V) WHERE Id=1"}, options)
	if err != nil {
		t.Fatal(err)
	}
	assertMutationInterval(t, r.Effective, 2, mutationTestInt(4))
	r, err = a.AnalyzeWriteShape(MutationWriteShape{Operation: "update", Table: "T", Columns: []string{"Id", "V"}, Values: map[string]interface{}{"Id": "1"}}, options)
	if err != nil {
		t.Fatal(err)
	}
	assertMutationInterval(t, r.Effective, 2, mutationTestInt(4))
}

func TestMutationCountQueueZeroDMLRows(t *testing.T) {
	a := mutationTestAnalyzer(t, "CREATE QUEUE Q(Id STRING(36) NOT NULL,Payload BYTES(MAX) NOT NULL) PRIMARY KEY(Id);")
	for _, sql := range []string{
		"INSERT INTO Q(Id,Payload) SELECT Id,Payload FROM Q WHERE FALSE",
		"INSERT OR IGNORE INTO Q(Id,Payload) SELECT Id,Payload FROM Q",
		"DELETE FROM Q WHERE FALSE",
	} {
		r, err := a.AnalyzeDML([]string{sql}, MutationCountOptions{Facts: []MutationCountRowFacts{{Rows: mutationTestInt(0)}}})
		if err != nil {
			t.Fatal(err)
		}
		assertMutationInterval(t, r.Bounds.Count, 0, mutationTestInt(0))
	}
	r, err := a.AnalyzeDML([]string{"INSERT OR IGNORE INTO Q(Id,Payload) VALUES('a',b'x')"}, MutationCountOptions{Facts: []MutationCountRowFacts{{Exists: mutationTestBool(true)}}})
	if err != nil {
		t.Fatal(err)
	}
	assertMutationInterval(t, r.Effective, 0, mutationTestInt(0))
	// The refinement applies to DML affected rows, not missing-key Ack or a
	// zero-row RECEIVE/RENEWLEASE response with unknown internal accounting.
	r, err = a.AnalyzeMutationsJSON([]byte(`[{"ack":{"queue":"Q","key":["missing"],"ignoreNotFound":true}}]`), MutationCountOptions{Facts: []MutationCountRowFacts{{Exists: mutationTestBool(false)}}})
	if err != nil {
		t.Fatal(err)
	}
	assertMutationInterval(t, r.Effective, 0, nil)
}
